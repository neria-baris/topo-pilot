"""DEPENDENCIES.md: package graph, per-file adjacency, entry-point trees, cycles, problems."""
import posixpath
from collections import defaultdict

from .render_pages import code

PKG_ROOT = "src/topo_pilot/"


def package_of(path):
    if not path.startswith(PKG_ROOT):
        return None
    rest = path[len(PKG_ROOT):]
    return rest.split("/")[0] if "/" in rest else "(root)"


def package_graph(model):
    counts, intra = defaultdict(int), defaultdict(int)
    pkgs = {package_of(p) for p in model["code"]} - {None}
    for src, dst in sorted({(s, d) for s, d, _k, _l in model["edges"]}):
        a, b = package_of(src), package_of(dst)
        if a and b:
            if a == b:
                intra[a] += 1
            else:
                counts[(a, b)] += 1
    return sorted(pkgs), counts, intra


def groups(model):
    """Entry-point groups: name -> root files."""
    out = defaultdict(list)
    for p in model["code"]:
        d = posixpath.dirname(p)
        if p == "src/topo_pilot/experiment/cli.py":
            out["topo_pilot.experiment.cli"].append(p)
        if d.startswith(("tools/", "tests/")) or d in ("tools", "tests"):
            out[d if d.count("/") else f"{d} (top level)"].append(p)
        elif not p.startswith("src/"):
            out[f"other: {d or '.'}"].append(p)
    return dict(sorted(out.items()))


def tree_lines(roots, out_edges):
    seen, lines = set(), []

    def walk(node, depth, stack):
        pad = "    " * depth
        if node in stack:
            lines.append(f"{pad}{node} (cycle)")
            return
        if node in seen:
            lines.append(f"{pad}{node} (see above)")
            return
        seen.add(node)
        lines.append(f"{pad}{node}")
        for child in out_edges.get(node, ()):
            walk(child, depth + 1, stack | {node})

    for root in sorted(roots):
        walk(root, 0, frozenset())
    return lines


def render(model):
    out, inn = model["out"], model["inn"]
    pkgs, counts, intra = package_graph(model)
    lines = ["# Dependencies", "",
             "Internal dependency graph over code files (imports, resolved dynamic imports and "
             "script invocations). Generated by `tools/build_code_index.py`; do not edit.", "",
             "## (a) Package-level graph (src/topo_pilot subpackages)", "",
             "Edge counts are file-to-file edges between different subpackages.", "",
             "| Package | Depends on (edge count) | Used by (edge count) | Edges inside |",
             "|---|---|---|---|"]
    for p in pkgs:
        to = ", ".join(f"{b} ({n})" for (a, b), n in sorted(counts.items()) if a == p)
        frm = ", ".join(f"{a} ({n})" for (a, b), n in sorted(counts.items()) if b == p)
        lines.append(f"| {p} | {to or '-'} | {frm or '-'} | {intra.get(p, 0)} |")
    lines += ["", "## (b) Per-file adjacency", "",
              "`->` = depends on; `<-` = depended on by.", ""]
    for p in model["code"]:
        lines.append(f"### {code(p)}")
        lines.append("- -> " + (", ".join(out.get(p, [])) or "none"))
        lines.append("- <- " + (", ".join(inn.get(p, [])) or "none"))
    lines += ["", "## (c) Dependency trees per entry-point group", "",
              "Nodes already expanded in the group are marked `(see above)`; a node that is "
              "its own ancestor is marked `(cycle)`.", ""]
    for name, roots in groups(model).items():
        lines += [f"### {name}", "", "```text"] + tree_lines(roots, out) + ["```", ""]
    lines += ["## (d) Import cycles (strongly connected components)", ""]
    for comp in model["cycles"]:
        lines.append(f"- {len(comp)} files: " + ", ".join(comp))
    if not model["cycles"]:
        lines.append("- none")
    lines += ["", "## (e) Unresolved and ambiguous imports", ""]
    for pr in model["problems"]:
        extra = (" candidates: " + ", ".join(pr["candidates"])) if pr["candidates"] else ""
        lines.append(f"- {pr['status']}: {pr['file']}:{pr['line']} {code(pr['text'])}{extra}")
    if not model["problems"]:
        lines.append("- none")
    return "\n".join(lines) + "\n"
